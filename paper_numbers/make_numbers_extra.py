#!/usr/bin/env python3
"""
paper_numbers/make_numbers_extra.py: the few manuscript numbers that make_numbers.py does not produce.

  1. Trainable parameter counts of the readout-swap readouts, MEASURED from the checkpoints in
     <results>/v3/gpu/full/ckpt (each readout is rebuilt with readout_swap/fullcommon.make_head, the checkpoint is
     loaded with strict=True, and the parameters of the module that exist in the checkpoint are counted). Readouts
     whose checkpoints are not present (they are not in the repository) are counted from the constructor and flagged
     in the comment; a strict load of a checkpoint into the same constructor implies the same count.
  2. The largest figure-mass loss of any local null at 30 deg rotation, pooled over all configurations
     (v3/scores/results.json; 20 deg is in numbers.tex as NullMaxLossTwenty).

Writes <out>/numbers_extra.tex (<out> = paper_numbers/output, or LAN_PAPER_OUT). Run: python paper_numbers/make_numbers_extra.py
"""
import json
import os
import sys
from pathlib import Path

import torch

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "readout_swap"))
sys.path.insert(0, str(REPO / "readout_swap" / "pilot"))
import fullcommon as FC  # noqa: E402
LP = FC.LP
ROOT = LP.RESULTS
OUT = Path(os.environ.get("LAN_PAPER_OUT") or Path(__file__).resolve().parent / "output")
OUT.mkdir(parents=True, exist_ok=True)

CK = ROOT / "v3" / "gpu" / "full" / "ckpt"
FSETS = (("dinov2_L12", "DinoTwelve", 768), ("dinov2_L6", "DinoSix", 768), ("siglip_L24", "SiglipTwentyFour", 1024),
         ("iie_shapenetc", "IIEFeat", 2048))
ARCHS = (("R1n", "RoneFixed"), ("R1", "Rone"), ("R2", "Rtwo"), ("R3", "Rthree"), ("R4", "Rfour"))
lines = ["% numbers_extra.tex: generated by paper_numbers/make_numbers_extra.py; do not edit by hand."]


def fmt_int(n):
    return f"{n:,}"


def fmt_m(n):
    return f"{n / 1e6:.2f}"


counts = {}
for fs, fsm, cin in FSETS:
    for ar, arm in ARCHS:
        torch.manual_seed(0)
        m = FC.make_head(ar, cin)
        names = {k for k, _ in m.named_parameters()}
        ck = CK / f"{fs}_{ar}_s0.pt"
        if ck.exists():
            sd = torch.load(ck, map_location="cpu", weights_only=False)
            m.load_state_dict(sd, strict=True)
            n = sum(v.numel() for k, v in sd.items() if k in names)
            how = f"measured: {ck.relative_to(ROOT)} loaded strict into fullcommon.make_head('{ar}', {cin}); sum of parameter tensors"
        else:
            n = sum(p.numel() for p in m.parameters())
            how = f"constructor only (checkpoint not present): fullcommon.make_head('{ar}', {cin})"
        counts[(fs, ar)] = n
        lines.append(f"% {how}")
        lines.append(f"\\newcommand{{\\RSParams{fsm}{arm}}}{{{fmt_int(n)}}}")
        lines.append(f"\\newcommand{{\\RSParams{fsm}{arm}M}}{{{fmt_m(n)}}}")

pw = [counts[(fs, a)] for fs, _, _ in FSETS for a in ("R1n", "R1")]
r4 = [counts[(fs, "R4")] for fs, _, _ in FSETS]
lines.append("% derived: min and max over feature sets of the pointwise (R1n, R1) and full-ASPP (R4) parameter counts above")
lines.append(f"\\newcommand{{\\RSParamsPointwiseMin}}{{{fmt_int(min(pw))}}}")
lines.append(f"\\newcommand{{\\RSParamsPointwiseMax}}{{{fmt_int(max(pw))}}}")
lines.append(f"\\newcommand{{\\RSParamsPointwiseMinM}}{{{min(pw) / 1e6:.3f}}}")
lines.append(f"\\newcommand{{\\RSParamsRfourMinM}}{{{fmt_m(min(r4))}}}")
lines.append(f"\\newcommand{{\\RSParamsRfourMaxM}}{{{fmt_m(max(r4))}}}")

R = LP.load_json(ROOT / "v3" / "scores" / "results.json")["models"]
best = None
for k, rec in R.items():
    if not k.startswith("null "):
        continue
    for key in ("drop_uni", "drop_alt"):
        d = rec["results"]["r_inside"]["all"][key]["30"]
        if best is None or d["mean"] > best[0]:
            best = (d["mean"], d["ci"], k, key)
v, c, k, key = best
def sg(x, plus=True, d=3):
    """Signed number; d decimals. A value that rounds to zero keeps its sign at 4 decimals (an interval bound of
    -0.0004 must not print as 0.000)."""
    r = round(x, d)
    if r == 0 and x != 0:
        d = 4
        r = round(x, d)
    if r == 0:
        return f"{0:.{d}f}"
    if r < 0:
        return f"\\ensuremath{{{r:.{d}f}}}"
    return f"\\ensuremath{{+{r:.{d}f}}}" if plus else f"{r:.{d}f}"


lines.append(f"% derived: max over the 15 local nulls and both rotations of m(illusory) - m(rotated 30 deg), r_inside, all "
             f"configurations, v3/scores/results.json > models > {k} > results > r_inside > all > {key} > 30")
lines.append(f"\\newcommand{{\\NullMaxLossThirty}}{{{sg(v)}}}")
lines.append(f"\\newcommand{{\\NullMaxLossThirtyCI}}{{[{sg(c[0], False, 4)}, {sg(c[1], False, 4)}]}}")
lines.append(f"% derived: whether that interval includes 0")
lines.append(f"\\newcommand{{\\NullMaxLossThirtyCIIncludesZero}}{{{'yes' if c[0] <= 0 <= c[1] else 'no'}}}")
(OUT / "numbers_extra.tex").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
